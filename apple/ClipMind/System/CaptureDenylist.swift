import AppKit
import Foundation

enum CaptureDenylist {
    private static let deniedBundleIDs: Set<String> = [
        // Password managers
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "2BUA8C4S2C.com.1password",
        "com.bitwarden.desktop",
        // Keychain
        "com.apple.keychainaccess",
        // Banking (representative bundle IDs)
        "com.chase",
        "com.chase.sig.android",
        "com.bankofamerica.BofA",
        "com.wf.wellsfargomobile",
        "com.citi.citimobile",
        "com.usaa.mobile.android.usaa",
        "com.capitalone.mobile",
    ]

    private static let neverDeniedBundleIDs: Set<String> = [
        "com.apple.Terminal",
        "com.googlecode.iterm2",
        "dev.warp.Warp-Stable",
    ]

    /// Markers from the nspasteboard.org conventions. Password managers and other apps
    /// set these on secrets and on throwaway or machine-generated content.
    static let ignoredPasteboardTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    static func shouldIgnore(pasteboardTypes: [NSPasteboard.PasteboardType]?) -> Bool {
        guard let pasteboardTypes else { return false }
        return pasteboardTypes.contains { ignoredPasteboardTypes.contains($0) }
    }

    static func shouldIgnore(bundleID: String?) -> Bool {
        guard let bundleID, !bundleID.isEmpty else {
            return false
        }

        if neverDeniedBundleIDs.contains(bundleID) {
            return false
        }

        return deniedBundleIDs.contains(bundleID)
    }
}
